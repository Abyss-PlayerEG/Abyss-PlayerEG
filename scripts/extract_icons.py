#!/usr/bin/env python3
"""Extract Nerd Font icon glyphs as SVG paths so cards render without the font.

Generates scripts/icon_paths.py — run this after changing GLYPHS or the font.
"""

import os
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

FONT_PATH = os.path.expanduser(
    "~/Library/Fonts/JetBrainsMonoNerdFont-Regular-v1.2.ttf"
)

GLYPHS = {
    "user": 0xF007,
    "pencil": 0xF040,
    "map": 0xF041,
    "briefcase": 0xF0B1,
    "calendar": 0xF133,
    "link": 0xF0C1,
    "folder": 0xF07B,
    "star": 0xF005,
    "users": 0xF0C0,
    "code": 0xF121,
}


def main():
    font = TTFont(FONT_PATH)
    upem = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyph_set = font.getGlyphSet()

    lines = [
        "#!/usr/bin/env python3",
        '"""Nerd Font icon outlines as SVG paths (generated by extract_icons.py)."""',
        "",
        f"UPM = {upem}",
        "",
        "ICONS = {",
    ]
    missing = []
    for name, cp in GLYPHS.items():
        gname = cmap.get(cp)
        if not gname:
            missing.append(f"{name} U+{cp:04X}")
            continue
        pen = SVGPathPen(glyph_set)
        glyph_set[gname].draw(pen)
        d = pen.getCommands().replace('"', "")
        lines.append(f'    "{name}": \'{d}\',')
    lines.append("}")

    if missing:
        print(f"⚠️  Missing glyphs: {', '.join(missing)}", file=sys.stderr)

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "icon_paths.py")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"✅ {out} ({len(GLYPHS) - len(missing)} icons, upem={upem})")


if __name__ == "__main__":
    main()

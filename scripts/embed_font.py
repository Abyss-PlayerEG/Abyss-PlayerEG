#!/usr/bin/env python3
"""Subset JetBrainsMono Nerd Font to the card charset and emit base64 data
so the SVG can embed it via @font-face (SVG-in-<img> cannot load webfonts).

Run this after changing CHARSET or installing a new font version.
Generates scripts/font_data.py.
"""

import base64
import io
import os
import sys

from fontTools import subset

FONT_PATH = os.path.expanduser(
    "~/Library/Fonts/JetBrainsMonoNerdFont-Regular-v1.2.ttf"
)
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "font_data.py")

# ASCII printable + symbols used by the card (· — … ❯)
CHARSET = "".join(chr(c) for c in range(0x20, 0x7F)) + "·—…❯"


def main():
    if not os.path.exists(FONT_PATH):
        print(f"❌ Font not found: {FONT_PATH}", file=sys.stderr)
        sys.exit(1)

    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.notdef_outline = True
    opts.recalc_bounds = True
    opts.hinting = False
    opts.glyph_names = False
    opts.legacy_kern = False
    opts.name_IDs = [1, 2]  # family + subfamily only

    font = subset.load_font(FONT_PATH, opts)
    ss = subset.Subsetter(options=opts)
    ss.populate(text=CHARSET)
    ss.subset(font)

    buf = io.BytesIO()
    subset.save_font(font, buf, opts)
    raw = buf.getvalue()
    b64 = base64.b64encode(raw).decode("ascii")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write('#!/usr/bin/env python3\n')
        f.write('"""JetBrainsMono subset for SVG embedding (generated by embed_font.py)."""\n\n')
        f.write('FONT_FORMAT = "truetype"\n')
        f.write("FONT_B64 = (\n")
        for i in range(0, len(b64), 100):
            f.write(f'    "{b64[i:i + 100]}"\n')
        f.write(")\n")

    print(
        f"✅ {OUT}  (subset {len(raw) // 1024} KB → base64 {len(b64) // 1024} KB, "
        f"{len(CHARSET)} chars)"
    )


if __name__ == "__main__":
    main()
